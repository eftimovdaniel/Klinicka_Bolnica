from pydantic import BaseModel
from typing import Optional  
from datetime import date, time  

# Модел за лекар - дефинира структурата на податоците за лекар во системот
# Според PDF: "За секој лекар се чуваат информации како име, презиме, специјалност, е-пошта и лозинка"
class Doctor(BaseModel):
    doctor_ID: int  # Уникатен идентификатор на лекарот (primary key од базата)
    name: str  # Име на лекарот
    surname: str  # Презиме на лекарот
    specialty: str  # Специјалност на лекарот (напр. "Кардиологија", "Хирургија")
    email: str  # Е-пошта адреса на лекарот (користи се за најава и комуникација)

# Модел за термин/преглед - дефинира структурата на податоците за закажан преглед
# Овој модел се користи за валидација на податоците при закажување на нов преглед
class Appointment(BaseModel):
    appointment_ID: Optional[int] = None  # ID на терминот (None ако е нов термин, auto-increment од базата)
    doctor_ID: int  # ID на лекарот со кого е закажан прегледот
    name: str  # Име на пациентот
    surname: str  # Презиме на пациентот
    phone: str  # Телефонски број на пациентот
    email: str  # Е-пошта адреса на пациентот
    date: str  # Датум на прегледот во формат "YYYY-MM-DD"
    time: str  # Време на прегледот во формат "HH:MM"
    message: Optional[str] = ""  # Опционална напомена од пациентот до лекарот
