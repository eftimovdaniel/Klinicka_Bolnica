"""
Детектор на интент - проверува што сака корисникот.

Користи едноставни клучни зборови (брзо и бесплатно).
Одлучува КОН КАДЕ да оди прашањето:
- "zakazi_termin"    → закажување нов термин (INSERT во база)
- "slobodni_termini" → преглед на слободни термини (само SELECT)
- "general"          → одговор од Gemini за општо прашање

ВАЖНО: Не извлекува име на лекар тука - тоа го прави Gemini подоцна
(со пристап до вистинската листа на лекари од базата).
"""


# Клучни зборови за ЗАКАЖУВАЊЕ (внимавај - редот на проверка е важен)
KLUCNI_ZBOROVI_ZAKAZI = [
    "закажи", "закажете", "закажување", "закаж",
    "сакам преглед", "сакам термин",
    "резервирај", "резервација",
    "запиши ме", "запиши го",
    "земи термин", "ми треба термин",
]

# Клучни зборови за СЛОБОДНИ ТЕРМИНИ (преглед, не закажување)
KLUCNI_ZBOROVI_SLOBODNI = [
    "слободен", "слободна", "слободни", "слободно",
    "кога е слободен", "кога е слободна",
    "кога ради", "кога работи",
]


def detektiraj_intent(prashanje: str) -> str:
    """
    Анализира прашање и враќа интент.

    Враќа: "zakazi_termin" или "slobodni_termini" или "general"
    """
    prashanje_lower = (prashanje or "").lower().strip()

    # ПРВО проверка за закажување (поспецифично)
    if any(zbor in prashanje_lower for zbor in KLUCNI_ZBOROVI_ZAKAZI):
        return "zakazi_termin"

    # ПОТОА проверка за слободни термини
    if any(zbor in prashanje_lower for zbor in KLUCNI_ZBOROVI_SLOBODNI):
        return "slobodni_termini"

    return "general"
