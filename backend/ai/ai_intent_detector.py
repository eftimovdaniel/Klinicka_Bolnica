"""
AI-driven intent detector со Groq (Llama 3.3 70B).

Зашто:
- Keyword detector-от пропушта природни варијации:
    "Dali možeš da mi zakažeš pregled?" - има „закажеш" не „закажи"
    "Бих сакал да одам кај лекар" - нема јасен keyword
    "Што имам утре?" - не е во ниту еден keyword list
- AI го разбира значењето, не само зборовите.

Стратегија:
- Главна функција: detektiraj_intent_so_ai(prashanje)
- Прима природен текст, враќа intent string
- Ако AI не одговори јасно → "general" (па одговара со општ AI)

Се користи КАКО fallback или замена за keyword detektorot во intent_detector.py.
"""

import re
from ai.groq_client import ask_ai


# Опис на поддржани интенти за AI
INTENT_SYSTEM_PROMPT = """
Ти си систем што класифицира корисничко прашање во еден од следните интенти.
Корисниците пишуваат на македонски јазик (кирилица или латиница).

ПОДДРЖАНИ ИНТЕНТИ:
- "zakazi_termin": корисникот сака да закаже преглед/термин кај лекар
  (пр. "Сакам преглед", "Закажи ми термин", "Резервирај", "Запиши ме")
- "otkazi_termin": корисникот сака да откаже постоечки термин
  (пр. "Откажи термин", "Не доаѓам", "Сторнирај")
- "prenesi_termin": корисникот сака да го префрли терминот на друг датум/време
  (пр. "Префрли го", "Одложи", "Промени датум", "Пренеси")
- "postavi_potsetnik": сака потсетник пред термин
  (пр. "Потсети ме", "Потсетник", "Напомени ми пред")
- "oceni_pregled": сака да даде оцена за завршен преглед
  (пр. "Оцена 5", "Беше одличен", "Давам петка", "Сакам да оценам")
- "trgni_ocena": сака да избрише дадена оцена
  (пр. "Тргни оцената", "Избриши ја оцената", "Отстрани")
- "slobodni_termini": прашува за слободни термини на лекар
  (пр. "Кога е слободен Петров?", "Кога работи?", "Слободни термини")
- "info_lekar": сака информации за конкретен лекар
  (пр. "Каков е д-р Петров?", "Кој е Стојанов?", "Инфо за лекар")
- "preporaka_lekar": опишува симптом/болка и сака препорака за специјалист
  (пр. "Боли ме коленото", "Имам грозница", "На кого да одам?")
- "rabotno_vreme": прашува работно време на оддел или болница
  (пр. "Кога е отворена лабораторијата?", "Работни денови")
- "lokacija": прашува каде се наоѓа оддел
  (пр. "Каде е гинекологија?", "Кој спрат?", "Соба?")
- "kontakti": бара телефон, мејл, итна помош
  (пр. "На кој број?", "Телефон за итна", "Контакт")
- "uslugi": прашува што нуди болницата
  (пр. "Кои услуги имате?", "Што нудите?", "Специјалности?")
- "objavi_vest": корисникот (директор) сака да објави вест од YouTube линк
  (пр. "Објави вест: https://youtube.com/...", "Публикувај од видео", "Креирај вест од youtube")
  ВАЖНО: ако пораката содржи youtube.com или youtu.be линк → секогаш „objavi_vest".
- "kreiraj_oglas": корисникот (директор) сака да креира оглас за работа
  (пр. "Креирај оглас за кардиолог", "Сакам нов оглас за медицинска сестра",
       "Објави оглас за хирург со рок 1 јуни")
- "izbrisi_vest_oglas": директор сака да избрише вест ИЛИ оглас
  (пр. "Избриши го најновиот оглас", "Избриши ја најновата вест",
       "Тргни го огласот ID 5", "Избриши вест 3")
- "zatvori_oglas": директор сака да затвори оглас (status = „истечен")
  (пр. "Затвори го огласот за кардиолог", "Затвори оглас ID 5",
       "Истечен е огласот за гинеколог", "Затвори ги сите огласи")
- "promeni_dezurstvo": директор сака да го промени дежурството на лекар
  (пр. "Префрли го д-р Петров за петок", "Премести дежурство на Иванов за 25.05",
       "Промени дежурство на Александра за утре 09:00")
- "statistika_oddeli": директор сака анализа/статистика на најпопуларни оддели
  (пр. "Кои се најпопуларни оддели?", "Топ 5 специјалности", "Колку прегледи по оддел?")
- "zavrshi_pregled": лекар сака да означи преглед како „завршен"
  (пр. "Заврши го прегледот на Иванов", "Заврши термин ID 42",
       "Заврши со дијагноза: грип, терапија: парацетамол")
- "istorija_pacient": лекар прашува колку пати/кога бил негов пациент
  (пр. "Колку пати беше Петар Иванов кај мене?", "Историја на пациент Иванов")
- "karton_pacient": лекар бара медицински картон/досие на пациент
  (пр. "Дај ми картон на Петар Иванов", "Покажи досие на Иванов")
- "moja_statistika": лекар прашува за свои лични статистики (прегледи, оцени)
  (пр. "Колку прегледи имам?", "Каква ми е просечната оцена?", "Моите статистики")
- "moj_raspored": лекар сака да види свои закажани прегледи (распоред)
  (пр. "Прикажи ми ги закажаните прегледи", "Што имам утре?", "Мојот распоред за оваа недела",
       "Кои се моите следни 5 прегледи?")
- "general": сè друго (општо прашање, поздрав, нејасно)

ВАЖНИ ПРАВИЛА:
1. Анализирај го целото значење, не само зборовите.
2. Ако корисникот пишува на латиница, претпостави дека е македонски на латиница
   (на пр. "zakazi" = "закажи", "pregled" = "преглед").
3. Ако прашањето не паѓа во ниту еден специфичен интент → "general".
4. Ако корисникот спомне само ИМЕ НА ЛЕКАР без друг контекст → "info_lekar".
5. Ако корисникот опишува БОЛКА или СИМПТОМ → "preporaka_lekar".

ОДГОВОР: Врати САМО име на интентот (на пр. "zakazi_termin"), без објаснувања,
без markdown, без наводници. Само еден збор од листата погоре.
""".strip()


# Множество валидни интенти за валидација на одговорот
VALIDNI_INTENTI = {
    "zakazi_termin",
    "otkazi_termin",
    "prenesi_termin",
    "postavi_potsetnik",
    "oceni_pregled",
    "trgni_ocena",
    "slobodni_termini",
    "info_lekar",
    "preporaka_lekar",
    "rabotno_vreme",
    "lokacija",
    "kontakti",
    "uslugi",
    "objavi_vest",
    "kreiraj_oglas",
    "izbrisi_vest_oglas",
    "zatvori_oglas",
    "promeni_dezurstvo",
    "statistika_oddeli",
    "zavrshi_pregled",
    "istorija_pacient",
    "karton_pacient",
    "moja_statistika",
    "moj_raspored",
    "general",
}


def detektiraj_intent_so_ai(prashanje: str) -> str:
    """
    Праша AI (Groq) да го класифицира прашањето во еден од поддржаните интенти.

    Враќа: име на интент (string). При било каква грешка → "general".
    """
    if not prashanje or not prashanje.strip():
        return "general"

    try:
        odgovor = ask_ai(prashanje.strip(), system_prompt=INTENT_SYSTEM_PROMPT)
    except Exception as e:
        print(f"[ai_intent] greshka pri AI: {e}")
        return "general"

    # Исчисти го одговорот
    cist = (odgovor or "").strip().lower()
    # Тргни markdown ``` или објаснувања
    cist = re.sub(r"^```\w*\s*", "", cist)
    cist = re.sub(r"\s*```$", "", cist)
    # Земи само првиот „збор" (intent_name)
    prv_red = cist.split("\n")[0].strip()
    prv_zbor = re.split(r"[\s,.!?:;()\"]+", prv_red)[0] if prv_red else ""

    # Валидирај
    if prv_zbor in VALIDNI_INTENTI:
        return prv_zbor

    # Ако AI врати нешто слично - barаj подниз
    for v in VALIDNI_INTENTI:
        if v in cist:
            return v

    print(f"[ai_intent] nevaliden odgovor: '{odgovor}' -> general")
    return "general"
