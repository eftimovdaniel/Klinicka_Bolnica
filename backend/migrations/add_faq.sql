-- Често поставувани прашања (FAQ) - база на знаење за AI агентот.
-- Кога пациент пита нешто (на пр. „Кое е работно време на лабораторијата?"),
-- агентот прво ги вади релевантните FAQ записи од оваа табела по клучни зборови,
-- па ги праќа на Google AI за поприроден одговор.
--
-- Безбедно за повторно извршување (CREATE TABLE IF NOT EXISTS + INSERT IGNORE).

CREATE TABLE IF NOT EXISTS FAQ (
  faq_ID INT NOT NULL AUTO_INCREMENT,
  -- Кратко прашање како што би го напишал корисникот.
  prashanje VARCHAR(500) NOT NULL,
  -- Готов одговор (може да биде долг, со форматирање).
  odgovor TEXT NOT NULL,
  -- Категорија (на пр. „работно_време", „локации", „процедури", „контакти").
  kategorija VARCHAR(80) DEFAULT NULL,
  -- Клучни зборови за матчинг (одделени со запирка). Помага кога прашањето на корисникот
  -- не е идентично со prashanje.
  klucni_zborovi TEXT DEFAULT NULL,
  -- 1 = активно (се користи), 0 = архивирано (не се прикажува).
  aktiven TINYINT(1) NOT NULL DEFAULT 1,
  -- Опционално: бројач на тоа колку пати било искористено (аналитика).
  pati_iskoristen INT NOT NULL DEFAULT 0,
  kreiran_na DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  azuriran_na DATETIME DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (faq_ID),
  KEY idx_faq_kategorija (kategorija),
  KEY idx_faq_aktiven (aktiven),
  -- FULLTEXT индекс за брзо пребарување по prashanje + odgovor + klucni_zborovi.
  FULLTEXT KEY ft_faq_search (prashanje, odgovor, klucni_zborovi)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

